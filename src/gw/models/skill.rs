#[repr(C, packed)]
pub struct AgentEffectsContext {
  /* +000 */ pub agent_id: u32,
  /* +004 */ pub buffs: Array<Buff>,
  /* +014 */ pub effects: Array<Effect>,
  /* +024 */
}

#[repr(C, packed)]
pub struct Buff {
  /* +000 */ pub skill_id: SkillId,
  /* +004 */ _unknown0: u32,
  /* +008 */ pub buff_id: u32,
  /* +00c */
  /** agent id of the target (0 if no target) */
  pub target_agent_id: u32,
  /* +010 */
}

#[repr(C, packed)]
pub struct Effect {
  /* +000 */ pub skill_id: SkillId,
  /* +004 */ pub attribute_level: u32,
  /* +008 */ pub effect_id: u32,
  /* +00c */
  /** non-zero means maintained enchantment - caster id */
  pub agent_id: u32,
  /* +010 */ pub duration: f32,
  /* +014 */ pub timestamp: u32,
  /* +018 */
}

#[repr(C, packed)]
pub struct SkillBar {
  /* +000 */ pub agent_id: u32,
  /* +004 */ pub skills: [SkillBarSkill; 8],
  /* +0a4 */ pub disabled: u32,
  /* +0a8 */ _unknown0: [u8; 0x8],
  /* +0b0 */ pub casting: u32,
  /* +0b4 */ _unknown1: [u8; 0x8],
  /* +0bc */
}

#[repr(C, packed)]
pub struct SkillBarSkill {
  /* +000 */ pub adrenaline_a: u32,
  /* +004 */ pub adrenaline_b: u32,
  /* +008 */ pub recharge: u32,
  /* +00c */ pub skill_id: SkillId,
  /* +010 */ event: u32,
  /* +014 */
}

#[repr(C, packed)]
pub struct Skill {
  /* +000 */ pub skill_id: SkillId,
  /* +004 */ _unknown0: u32,
  /* +008 */ campaign: u32,
  /* +00c */ skill_type: SkillType,
  /* +010 */ special: u32,
  /* +014 */ _unknown1: [u8; 0x14],
  /* +028 */ pub profession: ProfessionId,
  /* +029 */ pub attribute: AttributeId,
  /* +02a */ title: u16,
  /* +02c */ _unknown2: [u8; 0x8],
  /* +034 */ overcast: u8,
  /* +035 */ energy_cost: u8,
  /* +036 */ health_cost: u8,
  /* +037 */ _unknown3: [u8; 0x61],
  /* +098 */ name: u32,
  /* +09c */ concise_description: u32,
  /* +0a0 */ description: u32,
  /* +0a4 */
}

impl Skill {
  #[expect(unused)]
  pub fn get_energy_cost(&self) -> u8 {
    match self.energy_cost {
      11 => 15,
      12 => 25,
      _ => self.energy_cost,
    }
  }
}

