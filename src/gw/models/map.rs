use bitflags::bitflags;

#[derive(super::Enum!)]
#[repr(u32)]
pub enum InstanceType {
  Outpost,
  Explorable,
  Loading,
}

#[repr(C, packed)]
pub struct InstanceInfo {
  /* +000 */ pub terrain_info1: u32,
  /* +004 */ pub instance_type: InstanceType,
  /* +008 */ pub current_map_info: u32,
  /* +00c */ pub terrain_count: u32,
  /* +010 */ pub terrain_info2: u32,
  /* +014 */
}

bitflags! {
  #[repr(transparent)]
  #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
  pub struct AreaFlags: u32 {
    const IsOutpost    = 1 << 0x00;
    const IsExplorable = 1 << 0x12;
    const IsGuildHall  = 1 << 0x17;
  }
}

#[repr(C, packed)]
pub struct AreaInfo {
  /* +000 */ campaign: u32,
  /* +004 */ continent: u32,
  /* +008 */ region: u32,
  /* +00c */ region_type: u32,
  /* +010 */ pub flags: AreaFlags,
  /* +014 */ thumbnail_id: u32,
  /* +018 */ min_party_size: u32,
  /* +01c */ max_party_size: u32,
  /* +020 */ min_player_size: u32,
  /* +024 */ max_player_size: u32,
  /* +028 */ controlled_outpost_id: u32,
  /* +02c */ _unknown0: [u8; 0x50],
  /* +07c */
}

